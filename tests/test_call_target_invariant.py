"""Frozen call-target invariant (plan 0.14, Task 0.1).

``tests/goldens/calls/invariant_0121.json`` holds the target 0.12.1 resolved for every contract
call edge of the ``tests/fixtures/calls_invariant`` repositories (generated by
``scripts/perf/freeze_call_targets.py`` run against the 0.12.1 sources).  A later release must
never turn one of those ``symbol:`` targets into ``name:``.  Allowed differences:

* ``name:`` -> ``symbol:`` (a call that used to be unresolved now resolves);
* ``symbol:`` -> a different ``symbol:`` only when the 0.12.1 target lives in an auxiliary path
  (test/mock/stub) and the new one does not (the intended mock -> production change).

``EXPECTED_FIXED`` lists sites that were ``name:`` in 0.12.1 too (a defect of the current
extractor, not a regression) and must be ``symbol:`` once their task lands.
"""

from __future__ import annotations

import importlib.util
import json
from pathlib import Path

import pytest

from cortex.callresolve import _is_auxiliary, _symbol_path
from tests.golden_utils import GOLDEN_ROOT, TREE_SITTER_ONLY

ROOT = Path(__file__).resolve().parents[1]
FIXTURES = ROOT / "tests" / "fixtures" / "calls_invariant"
FROZEN = json.loads((GOLDEN_ROOT / "calls" / "invariant_0121.json").read_text(encoding="utf-8"))

# Fixtures whose `Ns::f()` / `A::B::f()` calls regressed to `name:` in 0.13.0 (Task 1.1) or whose
# `namespace A::B {` label is not parsed (Task 1.2).  Strict xfail: the task that fixes one must
# remove its entry here, or the unexpected pass fails the suite.
KNOWN_FAILING = {
    "split_namespace": "Task 1.1",
    "split_namespace_dup_basename": "Task 1.1",
    "split_namespace_indirect": "Task 1.1",
    "nested_namespace": "Task 1.2",
    "nested_namespace_blocks": "Task 1.1",
}

# Sites that are `name:` in 0.12.1 as well but must resolve to a `symbol:` once their task lands.
EXPECTED_FIXED = {
    "nested_namespace": ["app/c.cpp|2|f"],
}


def _load_freezer():
    spec = importlib.util.spec_from_file_location("freeze_call_targets", ROOT / "scripts" / "perf" / "freeze_call_targets.py")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def _violations(frozen: dict[str, str], current: dict[str, str]) -> list[str]:
    bad: list[str] = []
    for site, old in frozen.items():
        new = current.get(site)
        if not old.startswith("symbol:"):
            continue
        if new is None:
            bad.append(f"{site}: {old} -> (edge missing)")
        elif new == old:
            continue
        elif not new.startswith("symbol:"):
            bad.append(f"{site}: {old} -> {new}")
        elif not (_is_auxiliary(_symbol_path(old)[0]) and not _is_auxiliary(_symbol_path(new)[0])):
            bad.append(f"{site}: {old} -> {new} (not a mock -> production change)")
    return bad


def _param(name: str):
    marks = []
    if name in KNOWN_FAILING:
        marks.append(pytest.mark.xfail(strict=True, reason=f"{KNOWN_FAILING[name]} fixes this fixture; remove the mark there"))
    return pytest.param(name, id=name, marks=marks)


def test_every_fixture_is_frozen_and_vice_versa() -> None:
    on_disk = sorted(p.name for p in FIXTURES.iterdir() if p.is_dir())
    assert sorted(FROZEN) == on_disk
    assert set(KNOWN_FAILING) <= set(FROZEN) and set(EXPECTED_FIXED) <= set(FROZEN)


def test_frozen_namespace_targets_are_the_0121_ones() -> None:
    """Guard against freezing with the wrong code: 0.12.1 resolves these, 0.13.0 does not."""
    for name in ("split_namespace", "split_namespace_dup_basename", "split_namespace_indirect"):
        assert FROZEN[name]["app/caller.cpp|2|f"] == "symbol:lib/ns.cpp:f"
    assert FROZEN["nested_namespace_blocks"]["app/c.cpp|2|f"] == "symbol:lib/ab.cpp:f"
    assert FROZEN["nested_namespace"]["app/c.cpp|2|f"] == "name:f"


@TREE_SITTER_ONLY
@pytest.mark.parametrize("name", [_param(n) for n in sorted(FROZEN)])
def test_no_symbol_target_became_name(name: str) -> None:
    current = _load_freezer().call_targets(FIXTURES / name)
    problems = _violations(FROZEN[name], current)
    problems += [
        f"{site}: expected a symbol: target, got {current.get(site)}"
        for site in EXPECTED_FIXED.get(name, [])
        if not current.get(site, "").startswith("symbol:")
    ]
    assert not problems, "\n".join(problems)


def test_violation_rule_allows_only_the_documented_changes() -> None:
    frozen = {"a|1|f": "symbol:lib/x.cpp:f", "b|1|g": "symbol:mocks/m.cpp:g", "c|1|h": "name:h"}
    assert _violations(frozen, {"a|1|f": "symbol:lib/x.cpp:f", "b|1|g": "symbol:src/g.cpp:g", "c|1|h": "symbol:lib/h.cpp:h"}) == []
    assert len(_violations(frozen, {"a|1|f": "name:f"})) == 2  # a: became name, b: edge missing
    assert _violations({"a|1|f": "symbol:lib/x.cpp:f"}, {"a|1|f": "symbol:lib/y.cpp:f"})
    assert _violations({"b|1|g": "symbol:mocks/m.cpp:g"}, {"b|1|g": "symbol:mocks/n.cpp:g"})
