"""Pinned historical eval matrix at 7b0e6e0 (Task 0 baseline).

Runs the 17-task default matrix (4 modes, 68 rows) in-process through
``evals.run_evals.run_evals`` with ``--stdlib-tokens`` semantics and compares
precision / precision@3 / recall / file_recall / symbol_recall and the selected file list
per row with ``tests/goldens/evals/default_matrix.json`` (backend-independent).  The selected
file lists are pinned separately per backend (``default_files.<backend>.json``).  Tokens and
latency are excluded.  Later tasks must keep this file green unchanged ("the 17 historical tasks must
not regress"); Task 11 adds OSS rows to a *different* table.

Provenance, verified when the golden was created at 7b0e6e0: every precision / recall /
file_recall / symbol_recall / precision@3 value equals the corresponding 3-decimal value in
``evals/RESULTS.md`` (68/68 rows), under tree-sitter and under ``CORTEX_FORCE_REGEX=1``,
and the two backends produce identical rows.

Discrepancy found while pinning (not a plan assumption): ``python3 evals/run_evals.py`` is
**not** deterministic by itself.  The fixture repos are committed with wall-clock
timestamps, and ``bundle.generate_bundle`` weights commit recency by ``authored_at``
differences, so when two fixture commits straddle a second boundary one row can flip
(observed: ``skeleton_off`` precision 0.5 vs 0.4 for the markdown-setup task).  This test
fixes ``GIT_AUTHOR_DATE``/``GIT_COMMITTER_DATE`` so the matrix is reproducible.
"""

from __future__ import annotations

from pathlib import Path

import pytest

from evals.run_evals import GOLD_TASKS, run_evals
from tests.baseline_helpers import fixed_git_env
from tests.golden_utils import TREE_SITTER_ONLY, assert_golden

DEFAULT_MODES = ["pagerank", "bfs", "skeleton_on", "skeleton_off"]
METRICS = ("precision", "precision_at_3", "recall", "file_recall", "symbol_recall")


def _matrix(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> list[dict]:
    fixed_git_env(monkeypatch)
    # The OSS fixtures (Task 11) are scored separately (tests/test_evals.py) and
    # never enter ``rows``; skip them here to keep the historical check fast.
    _, rows = run_evals(tmp_path / "RESULTS.md", stdlib_tokens=True, oss=False)
    return [
        {
            "repo": row["task"].repo,
            "task": row["task"].description,
            "mode": row["mode"],
            **{metric: row[metric] for metric in METRICS},
            "files": list(row["files"]),
        }
        for row in rows
    ]


def _metrics_only(matrix: list[dict]) -> list[dict]:
    return [{k: v for k, v in row.items() if k != "files"} for row in matrix]


def _files_only(matrix: list[dict]) -> list[dict]:
    return [{k: row[k] for k in ("repo", "task", "mode", "files")} for row in matrix]


def _check_shape(matrix: list[dict]) -> None:
    untagged = [task for task in GOLD_TASKS if not task.tags]
    assert len(untagged) == 17
    assert len(matrix) == 17 * len(DEFAULT_MODES)
    assert sorted({row["mode"] for row in matrix}) == sorted(DEFAULT_MODES)
    assert {row["task"] for row in matrix} == {task.description for task in untagged}


@TREE_SITTER_ONLY
def test_default_matrix_golden_treesitter(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    matrix = _matrix(tmp_path, monkeypatch)

    _check_shape(matrix)
    assert_golden("evals/default_matrix.json", _metrics_only(matrix))
    assert_golden("evals/default_files.treesitter.json", _files_only(matrix))


def test_default_matrix_golden_regex(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    monkeypatch.setenv("CORTEX_FORCE_REGEX", "1")
    matrix = _matrix(tmp_path, monkeypatch)

    _check_shape(matrix)
    # Metrics are identical to the tree-sitter matrix at 7b0e6e0 -- one golden covers both
    # backends.  The *order* of selected files differs for one Qt task, hence per-backend
    # file-list goldens.
    assert_golden("evals/default_matrix.json", _metrics_only(matrix))
    assert_golden("evals/default_files.regex.json", _files_only(matrix))


def test_results_markdown_is_written_with_the_stdlib_command(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    fixed_git_env(monkeypatch)
    markdown, rows = run_evals(tmp_path / "RESULTS.md", stdlib_tokens=True, oss=False)

    assert (tmp_path / "RESULTS.md").read_text(encoding="utf-8") == markdown
    assert "Generated by `python3 evals/run_evals.py --stdlib-tokens`." in markdown
    assert len(rows) == 68
